"""Copy the simulator sources from sim/ into the PokeRogue checkout.

Vite only loads test files that live inside pokerogue/ (symlinks out of it fail), so sim/ is
the source of truth and pokerogue/test/rl/ holds a generated copy, plus one tiny test file per
simulator slot (Vitest runs each test file in its own worker, so N files = N simulators sharing
one Vitest process). SimClient.launch() runs this automatically; run it by hand before starting a
server yourself:

    python -m pokerogue_rl.install_sim
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIM_SRC = ROOT / "sim"
SIM_DEST = ROOT / "pokerogue" / "test" / "rl"
MAX_SIMS = 32  # simulator slots one Vitest process can host


def sim_test_file(index: int) -> str:
    return f"sim-{index:02d}.test.ts"


def install_sim() -> list[Path]:
    """Sync sim/*.ts and the per-simulator test files into the checkout; return files written."""
    SIM_DEST.mkdir(exist_ok=True)
    wanted: dict[str, bytes] = {src.name: src.read_bytes() for src in SIM_SRC.glob("*.ts")}
    for i in range(MAX_SIMS):
        wanted[sim_test_file(i)] = (
            "// Generated by pokerogue_rl.install_sim; edit sim/ instead.\n"
            'import { defineSimServer } from "./sim-server";\n\n'
            f"defineSimServer({i});\n"
        ).encode()

    written = []
    for name, content in wanted.items():
        dest = SIM_DEST / name
        if not dest.exists() or dest.read_bytes() != content:
            dest.write_bytes(content)
            written.append(dest)
    for stale in SIM_DEST.glob("*.ts"):
        if stale.name not in wanted:
            stale.unlink()
    return written


if __name__ == "__main__":
    written = install_sim()
    print(f"wrote {len(written)} file(s) to {SIM_DEST}" if written else "simulator already up to date")
